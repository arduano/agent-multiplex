export type NativeDiagnosticEventType = typeof copilotDiagnosticTypes[number] | "unknown";
const knownCopilotTypes: ReadonlySet<string> = new Set(copilotDiagnosticTypes);

export function nativeDiagnosticEventType(harness: Harness, nativeType: string): NativeDiagnosticEventType {
  return harness === "copilot" && knownCopilotTypes.has(nativeType)
    ? nativeType as NativeDiagnosticEventType : "unknown";
}
