import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { build } from 'esbuild';
import { buildChatStyles } from '../build/styles.mjs';
import { buildChatNotices } from '../build/notices.mjs';
import { buildPdfAssets } from '../build/pdf-assets.mjs';
const here = dirname(fileURLToPath(import.meta.url)), module = resolve(here, '..'), framework = resolve(module, '../..'), out = resolve(module, '.build/browser');
const require = createRequire(resolve(module, 'package.json'));
const types = spawnSync(process.execPath, [resolve(framework, 'node_modules/typescript/bin/tsc'), '--project', resolve(module, 'tsconfig.json')], { stdio: 'inherit' });
if (types.status !== 0) process.exit(types.status ?? 1);
await mkdir(out, { recursive: true });
const client = await build({ entryPoints: [resolve(module, 'src/index.ts')], bundle: true, outfile: resolve(out, 'index.js'), platform: 'browser', format: 'esm', target: 'es2023', external: ['react', 'react/*', 'react-dom', 'react-dom/*'], metafile: true, minify: true, sourcemap: true, logLevel: 'warning' });
const renderer = await build({ entryPoints: [resolve(module, 'src/renderers/mermaid-frame.ts')], bundle: true, outfile: resolve(out, 'renderers/mermaid-frame.js'), platform: 'browser', format: 'iife', target: 'es2023', metafile: true, minify: true, logLevel: 'warning' });
const styles = await buildChatStyles({ outdir: out });
const pdf = await buildPdfAssets({ outdir: out });
await buildChatNotices({ outdir: out, metafiles: [client.metafile, renderer.metafile, styles.metafile, pdf.metafile] });
const outputs = { entry: 'index.js', styles: 'chat.css', diagramRenderer: 'renderers/mermaid-frame.js', pdfResources: pdf.base, reactPeer: '19.2.8', browserOnly: true, licenses: 'THIRD_PARTY_LICENSES.txt' };
await writeFile(resolve(out, 'manifest.json'), JSON.stringify(outputs, null, 2)+'\n');
process.stdout.write(JSON.stringify({ built: true, ...outputs })+'\n');
